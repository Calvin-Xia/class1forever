"""Deterministic, complete Unicode font shards; no page text or private data input.

python scripts/font-subsets.py generate   # pinned optional requirements-fonts.txt
python scripts/font-subsets.py verify     # cmap, UVS, metrics, outlines, variations
"""
import argparse
import hashlib
import io
import json
import tempfile
from pathlib import Path

import brotli
import fontTools
from fontTools import subset
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
INPUT = ROOT / 'font-sources'
OUTPUT = ROOT / 'public/fonts'
MANIFEST = OUTPUT / 'manifest.json'
CSS = ROOT / 'src/styles/fonts.css'
VERSIONS = {'fontTools': '4.62.1', 'brotli': '1.2.0'}
NAMES = ['Noto Sans SC', 'Noto Serif SC', 'DM Serif Display']


def sha(data):
    return hashlib.sha256(data).hexdigest()


def axes(font):
    return [{'tag': a.axisTag, 'minimum': a.minValue, 'maximum': a.maxValue,
             'default': a.defaultValue} for a in font['fvar'].axes] if 'fvar' in font else []


def ranges(points):
    groups = []
    for point in sorted(points):
        if groups and point == groups[-1][1] + 1:
            groups[-1][1] = point
        else:
            groups.append([point, point])
    return ','.join(f'U+{a:X}' + (f'-{b:X}' if a != b else '') for a, b in groups)


def parse_ranges(value):
    result = set()
    for item in value.split(','):
        bounds = [int(v, 16) for v in item.removeprefix('U+').split('-')]
        result.update(range(bounds[0], bounds[-1] + 1))
    return result


def uvs(font):
    # A format 14 cmap holds variation sequences outside getBestCmap().
    result = {}
    for table in font['cmap'].tables:
        if table.format == 14:
            for selector, items in table.uvsDict.items():
                for point, glyph in items:
                    result[(selector, point)] = glyph
    return result


def css_text(families):
    blocks = ['/* Generated by scripts/font-subsets.py; full upstream cmap across all shards.\n'
              '   Sources and SIL OFL: public/fonts/README.md + font-sources/manifest.json. */']
    for family in families:
        weight = ' '.join(str(int(v)) for v in [family['axes'][0]['minimum'], family['axes'][0]['maximum']]) if family['axes'] else '400'
        for shard in family['shards']:
            blocks.append("@font-face {\n"
                          f"    font-family: '{family['family']}';\n"
                          '    font-style: normal;\n'
                          f'    font-weight: {weight};\n'
                          '    font-display: swap;\n'
                          f"    src: url('/fonts/{shard['file']}') format('woff2');\n"
                          f"    unicode-range: {shard['unicodeRange']};\n" + '}')
    return '\n\n'.join(blocks) + '\n'


def sources():
    source_manifest = json.loads((INPUT / 'manifest.json').read_text(encoding='utf-8'))
    for meta in source_manifest['fonts']:
        assert sha((INPUT / meta['file']).read_bytes()) == meta['sha256'], 'Complete source SHA mismatch'
        if 'unicodeRange' in meta:
            assert parse_ranges(meta['unicodeRange']) == set(TTFont(INPUT / meta['file']).getBestCmap()), 'Source cmap metadata drift'
    return source_manifest


def generate():
    assert fontTools.__version__ == VERSIONS['fontTools'], 'Use requirements-fonts.txt'
    assert brotli.__version__ == VERSIONS['brotli'], 'Use requirements-fonts.txt'
    source_manifest = sources()
    families = []
    subset_dir = OUTPUT / 'subsets'
    subset_dir.mkdir(exist_ok=True)
    for family_name, meta in zip(NAMES, source_manifest['fonts']):
        source_data = (INPUT / meta['file']).read_bytes()
        original = TTFont(io.BytesIO(source_data), recalcTimestamp=False)
        # WOFF2 decode reconstructs the complete CJK glyph table. Decode once into
        # an in-memory SFNT; each shard starts from those same preserved tables.
        if family_name != 'DM Serif Display':
            print(f'{family_name}: decoding complete source once', flush=True)
            original.flavor = None
            decoded = io.BytesIO()
            original.save(decoded, reorderTables=False)
            source_data = decoded.getvalue()
        points = sorted(original.getBestCmap())
        # Stable Unicode order only: every original encoded character is retained.
        # Latin/symbols < U+3000 form a reusable core; all others use 256-point shards.
        remaining = [point for point in points if point >= 0x3000]
        chunks = [[p for p in points if p < 0x3000]]
        chunks.extend(remaining[index:index + 256] for index in range(0, len(remaining), 256))
        if family_name == 'DM Serif Display':
            chunks = [points]  # 32 kB, no benefit in recompressing it.
        family = {'family': family_name, 'sourceFile': meta['file'], 'sourceSha256': meta['sha256'],
                  'sourceBytes': meta['bytes'], 'unicodeCharacters': len(points),
                  'axes': axes(original), 'variationSequences': len(uvs(original)), 'shards': []}
        slug = meta['file'].split('.')[0]
        for index, chunk in enumerate(chunks):
            if not chunk:
                continue
            if family_name == 'DM Serif Display':
                data = source_data
                relative = meta['file']
            else:
                font = TTFont(io.BytesIO(source_data), recalcTimestamp=False)
                options = subset.Options()
                options.recalc_timestamp = False
                options.layout_features = ['*']
                options.notdef_outline = True
                # Retain variation selectors whose base characters are in this shard.
                selectors = {selector for selector, point in uvs(original) if point in chunk}
                subsetter = subset.Subsetter(options=options)
                subsetter.populate(unicodes=chunk + sorted(selectors))
                subsetter.subset(font)
                font.flavor = 'woff2'
                buffer = io.BytesIO()
                font.save(buffer, reorderTables=False)
                data = buffer.getvalue()
                relative = f'subsets/{slug}-{index:03d}.{sha(data)[:12]}.woff2'
            (OUTPUT / relative).write_bytes(data)
            family['shards'].append({'file': relative, 'sha256': sha(data), 'bytes': len(data),
                                     'unicodeCharacters': len(chunk), 'unicodeRange': ranges(chunk)})
            if index % 20 == 0:
                print(f'{family_name}: {index + 1}/{len(chunks)}', flush=True)
        families.append(family)
    result = {'schemaVersion': 2, 'repository': source_manifest['repository'],
              'commit': source_manifest['commit'], 'tools': VERSIONS,
              'partition': 'Unicode ascending; < U+3000 core; remaining groups of 256 code points',
              'families': families}
    MANIFEST.write_text(json.dumps(result, ensure_ascii=False, indent=4) + '\n', encoding='utf-8')
    CSS.write_text(css_text(families), encoding='utf-8')
    print(f'Complete source bytes: {sum(f["sourceBytes"] for f in families):,}; '
          f'all shard bytes: {sum(s["bytes"] for f in families for s in f["shards"]):,}')


def drawing(font, glyph, location):
    glyphs = font.getGlyphSet(location=location)
    pen = DecomposingRecordingPen(glyphs)
    glyphs[glyph].draw(pen)
    return pen.value


def metric_deltas(font, glyph, mapping_name):
    if 'HVAR' not in font:
        return []
    table = font['HVAR'].table
    mapping = getattr(table, mapping_name)
    if mapping is None and mapping_name != 'AdvWidthMap':
        return []
    index = mapping.mapping[glyph] if mapping else font.getGlyphID(glyph)
    if index == 0xFFFFFFFF:
        return []
    outer, inner = index >> 16, index & 0xFFFF
    data = table.VarStore.VarData[outer]
    result = []
    for region_index, value in zip(data.VarRegionIndex, data.Item[inner]):
        if value:
            region = table.VarStore.VarRegionList.Region[region_index]
            result.append((tuple((a.StartCoord, a.PeakCoord, a.EndCoord) for a in region.VarRegionAxis), value))
    return sorted(result)


def verify():
    sources()
    manifest = json.loads(MANIFEST.read_text(encoding='utf-8'))
    assert CSS.read_text(encoding='utf-8') == css_text(manifest['families']), 'CSS drift'
    for family in manifest['families']:
        original = TTFont(INPUT / family['sourceFile'], recalcTimestamp=False)
        original_cmap = original.getBestCmap()
        union = set()
        union_uvs = {}
        for index, shard in enumerate(family['shards']):
            data = (OUTPUT / shard['file']).read_bytes()
            assert sha(data) == shard['sha256'] and len(data) == shard['bytes'], 'Shard SHA/size mismatch'
            font = TTFont(io.BytesIO(data), recalcTimestamp=False)
            cmap = font.getBestCmap()
            expected = parse_ranges(shard['unicodeRange'])
            assert set(cmap) == expected, 'Shard cmap does not match CSS Unicode range'
            assert not union.intersection(expected), 'Overlapping shard ranges'
            union.update(expected)
            assert axes(font) == axes(original) == family['axes'], 'Variable weight axis changed'
            if 'avar' in original:
                assert font['avar'].segments == original['avar'].segments, 'Weight-axis mapping changed'
            # Compare complete design-space deltas and default outlines for every encoded glyph.
            # This checks all weights, rather than only sampling a few instantiated weights.
            for point, glyph in cmap.items():
                source_glyph = original_cmap[point]
                assert font['hmtx'][glyph] == original['hmtx'][source_glyph], f'Metrics changed at U+{point:X}'
                if 'vmtx' in original:
                    assert font['vmtx'][glyph] == original['vmtx'][source_glyph], f'Vertical metrics changed at U+{point:X}'
                for mapping in ['AdvWidthMap', 'LsbMap', 'RsbMap']:
                    assert metric_deltas(font, glyph, mapping) == metric_deltas(original, source_glyph, mapping), f'Variable metrics changed at U+{point:X}'
                assert drawing(font, glyph, {}) == drawing(original, source_glyph, {}), f'Outline changed at U+{point:X}'
                if 'gvar' in original:
                    left = [(v.axes, v.coordinates) for v in font['gvar'].variations[glyph]]
                    right = [(v.axes, v.coordinates) for v in original['gvar'].variations[source_glyph]]
                    assert left == right, f'Weight variation deltas changed at U+{point:X}'
            # UVS glyph names can be renumbered; compare sequence semantics and outlines.
            for key, glyph in uvs(font).items():
                assert key not in union_uvs, 'Overlapping variation sequence'
                union_uvs[key] = glyph
                source_glyph = uvs(original)[key]
                assert (glyph is None) == (source_glyph is None), 'Default UVS changed'
                if glyph:
                    assert drawing(font, glyph, {}) == drawing(original, source_glyph, {}), 'UVS outline changed'
                    if 'gvar' in original:
                        assert [(v.axes, v.coordinates) for v in font['gvar'].variations[glyph]] == [
                            (v.axes, v.coordinates) for v in original['gvar'].variations[source_glyph]], 'UVS weight deltas changed'
            if index % 20 == 0:
                print(f'{family["family"]}: verified {index + 1}/{len(family["shards"])}', flush=True)
        assert union == set(original_cmap), 'Incomplete original character coverage'
        assert set(union_uvs) == set(uvs(original)), 'Incomplete variation-sequence coverage'
        print(f'{family["family"]}: {len(union):,} cmap characters, {len(union_uvs)} UVS, '
              f'{len(family["shards"])} shards; cmap/outlines/metrics/weight deltas PASS', flush=True)


def reproduce():
    global OUTPUT, MANIFEST, CSS
    original_output, original_manifest, original_css = OUTPUT, MANIFEST, CSS
    expected = json.loads(original_manifest.read_text(encoding='utf-8'))
    temporary_root = ROOT / '.wrangler'
    temporary_root.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='font-rebuild-', dir=temporary_root) as directory:
        assert Path(directory).resolve().parent == temporary_root.resolve(), 'Unsafe temporary output directory'
        OUTPUT = Path(directory) / 'fonts'
        OUTPUT.mkdir()
        MANIFEST = OUTPUT / 'manifest.json'
        CSS = Path(directory) / 'fonts.css'
        generate()
        assert MANIFEST.read_bytes() == original_manifest.read_bytes(), 'Rebuilt manifest differs'
        assert CSS.read_bytes() == original_css.read_bytes(), 'Rebuilt CSS differs'
        for family in expected['families']:
            for shard in family['shards']:
                assert (OUTPUT / shard['file']).read_bytes() == (original_output / shard['file']).read_bytes(), 'Rebuilt font differs'
        print('Independent rebuild: all WOFF2 bytes, manifest and CSS identical', flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['generate', 'verify', 'reproduce'])
    args = parser.parse_args()
    {'generate': generate, 'verify': verify, 'reproduce': reproduce}[args.command]()
